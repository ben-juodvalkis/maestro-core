//! Regenerates the committed TypeScript bindings under `maestro-api/bindings/`.
//!
//! CI runs `cargo run -p maestro-api --bin gen-ts && git diff --exit-code` so a
//! schema change that isn't reflected in the committed bindings fails the build
//! (spec §3.6 — binding drift is a build error).

use ts_rs::TS;

fn main() {
    let dir = concat!(env!("CARGO_MANIFEST_DIR"), "/bindings");
    maestro_api::EngineConfig::export_all_to(dir).unwrap();
    maestro_api::Command::export_all_to(dir).unwrap();
    maestro_api::CommandResult::export_all_to(dir).unwrap();
    maestro_api::LoadMeta::export_all_to(dir).unwrap();
    maestro_api::Event::export_all_to(dir).unwrap();
    maestro_api::Snapshot::export_all_to(dir).unwrap();

    // FR2 (ADR-100): the app bundle's half of the schema-fingerprint
    // handshake — the same hash build.rs embeds in every engine artifact.
    // Computed AFTER the exports above so it always reflects what was just
    // written; the regen gate above keeps the committed copy honest.
    let fp = maestro_api::fingerprint::fingerprint_bindings(std::path::Path::new(dir)).unwrap();
    std::fs::write(
        format!("{dir}/{}", maestro_api::fingerprint::FINGERPRINT_BINDING_FILE),
        format!(
            "// Generated by gen-ts (FR2, ADR-100) — a hash over the sibling binding\n\
             // files. The backends assert this against the fingerprint embedded in the\n\
             // engine artifact at init; mismatch or absence is a hard init failure.\n\
             // Regenerate: cargo run -p maestro-api --features ts --bin gen-ts\n\
             export const MAESTRO_SCHEMA_FINGERPRINT = '{fp}';\n"
        ),
    )
    .unwrap();
    println!("TypeScript bindings written to {dir}");
}
